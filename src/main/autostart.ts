import { app } from "electron";

/**
 * Запуск вместе с Windows, сразу в трей.
 *
 * Приложение не просто окно: companion держит вход в систему, наблюдатель
 * доски шлёт уведомления о задачах, а диктовка и снимки экрана висят на
 * глобальных клавишах. Всё это работает, только пока процесс жив, и человеку,
 * который рассчитывает нажать горячую клавишу в любой момент, приходилось
 * каждое утро вспоминать, что приложение надо запустить руками.
 *
 * Поэтому автозапуск открывает окно не сразу: стартуем свёрнутыми в трей.
 * Окно, выскакивающее поверх всего при каждом входе в систему, раздражает
 * ровно тех, кому автозапуск и нужен — тех, у кого приложение работает весь
 * день.
 */

/**
 * Признак скрытого старта.
 *
 * Передаётся аргументом, а не читается из настроек, потому что проверяется до
 * создания окна и должен действовать и при ручном запуске с этим ключом —
 * этим удобно проверять поведение, не трогая настройки системы.
 */
export const HIDDEN_FLAG = "--hidden";

/**
 * Стартовать ли свёрнутыми.
 *
 * Отдельная чистая функция: разбор аргументов командной строки на Windows
 * полон частностей (electron подставляет свои ключи, у упакованной и
 * неупакованной сборки разный argv), и проверять его тестом надёжнее, чем
 * глазами.
 */
export function shouldStartHidden(argv: readonly string[]): boolean {
  return argv.some((arg) => arg === HIDDEN_FLAG || arg === "--start-hidden");
}

/**
 * Включён ли автозапуск.
 *
 * Спрашиваем систему, а не своё сохранённое значение: человек мог выключить
 * автозапуск в диспетчере задач Windows, и тогда наша галочка врала бы.
 */
export function isAutostartEnabled(): boolean {
  // Речь только о запуске через `npm run dev`: там запись указывала бы на
  // electron.exe из node_modules, этот путь протухает после первой же
  // пересборки, и в автозагрузке у человека остаётся мусор. Любая собранная
  // сборка — установленная, распакованная или портабл — считается упакованной
  // и автозапуск поддерживает.
  if (!app.isPackaged) return false;
  try {
    return app.getLoginItemSettings({
      path: autostartTargetPath(),
      args: [HIDDEN_FLAG],
    }).openAtLogin;
  } catch {
    // Linux без поддержки автозапуска в Electron — не повод падать.
    return false;
  }
}

export function setAutostart(enabled: boolean): boolean {
  if (!app.isPackaged) return false;
  try {
    app.setLoginItemSettings({
      openAtLogin: enabled,
      // Путь задаём явно: без него Windows в некоторых случаях записывает в
      // автозагрузку путь к процессу-обновлятору, а не к самому приложению,
      // а для портабл-сборки — путь во временную папку (см. выше).
      path: autostartTargetPath(),
      args: [HIDDEN_FLAG],
    });
    return isAutostartEnabled();
  } catch {
    return false;
  }
}

/**
 * Путь, который надо прописать в автозагрузку.
 *
 * Для портабл-сборки это не `process.execPath`. Портабл распаковывается во
 * временную папку и запускается оттуда, поэтому execPath указывает внутрь
 * %TEMP% — Windows её вычистит, и в автозагрузке останется запись в никуда.
 * electron-builder кладёт настоящий путь к .exe в PORTABLE_EXECUTABLE_FILE,
 * его и берём, когда он есть.
 */
export function autostartTargetPath(): string {
  return process.env.PORTABLE_EXECUTABLE_FILE?.trim() || process.execPath;
}

/** Поддерживается ли автозапуск в этой сборке и на этой системе. */
export function isAutostartSupported(): boolean {
  return app.isPackaged && process.platform !== "linux";
}
