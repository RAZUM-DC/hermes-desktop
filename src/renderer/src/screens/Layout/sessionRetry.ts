/**
 * Правила фонового дожидания списка чатов.
 *
 * Зачем отдельным модулем: решения здесь маленькие, но важные — через сколько
 * повторить и когда перестать молчать. Внутри компонента их не проверить, а
 * ошибиться в них легко: слишком рано сказать «не удалось» — соврать, слишком
 * поздно — оставить человека гадать.
 *
 * Общая логика такая. Список чатов приходит с сервера, и путь до него длинный:
 * десктоп → companion → релей → рантайм пользователя. Любое звено может быть
 * не готово в первые секунды после запуска, а бывает, что и дольше. Раньше
 * приложение делало одну попытку, молча её проглатывало и рисовало «Нет
 * чатов» — неотличимо от настоящей потери истории. Теперь попытки не
 * кончаются: они лишь редеют, выходя на ту же минуту, с какой список
 * обновляется в спокойном состоянии.
 */

/** Паузы между попытками, мс. Дальше последней — повтор раз в минуту. */
export const RETRY_BACKOFF_MS = [
  2_000, 4_000, 8_000, 15_000, 30_000, 60_000,
] as const;

/**
 * Со скольки неудач подряд признаём вслух, что не загрузилось.
 *
 * Первые секунды молчим: при живом сервере всё поднимается за две-три, и
 * мигать в это время словом «не удалось» — врать раньше времени.
 */
export const RETRY_ATTEMPTS_BEFORE_ADMITTING_FAILURE = 3;

export type SessionsLoadState = "loading" | "ready" | "failed";

/**
 * Через сколько повторить после `attempt`-й неудачи подряд (нумерация с 1).
 * Отрицательные и нулевые значения трактуем как первую попытку — вызывающий
 * код не обязан следить за краями.
 */
export function retryDelayMs(attempt: number): number {
  const index = Math.min(
    Math.max(Math.trunc(attempt), 1) - 1,
    RETRY_BACKOFF_MS.length - 1,
  );
  return RETRY_BACKOFF_MS[index];
}

/**
 * Что показывать после очередной неудачи.
 *
 * Уже показанный список не стираем ни при какой неудаче: лучше слегка
 * устаревшие чаты, чем пустота на их месте.
 */
export function loadStateAfterFailure(
  previous: SessionsLoadState,
  attempt: number,
): SessionsLoadState {
  if (previous === "ready") return "ready";
  return attempt >= RETRY_ATTEMPTS_BEFORE_ADMITTING_FAILURE
    ? "failed"
    : "loading";
}
