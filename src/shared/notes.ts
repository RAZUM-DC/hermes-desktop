/**
 * Заметки: общие типы для main, preload и рендерера.
 *
 * Хранятся на машине пользователя, никуда не уходят и ни с чем не
 * синхронизируются. Это блокнот под рукой, а не ещё одно место, где заводится
 * переписка: банк памяти наполняет ассистент сам, а сюда человек пишет то,
 * что хочет держать при себе.
 */

/** Файл или картинка, приложенные к заметке. */
export interface NoteAttachment {
  id: string;
  /** Имя исходного файла — его и показываем человеку. */
  name: string;
  mime: string;
  size: number;
  /**
   * Можно ли показать содержимое прямо в заметке. Считается один раз при
   * прикреплении, а не при каждой отрисовке: тип определяется по расширению
   * исходного файла, которого после копирования в хранилище уже не видно.
   */
  image: boolean;
  addedAt: number;
}

export interface Note {
  id: string;
  /**
   * Заголовок, который человек задал руками. Пустая строка значит, что он его
   * не давал и показывать надо автоматический — см. `autoNumber`.
   */
  title: string;
  /**
   * Номер для автоматического заголовка («Заметка 3»).
   *
   * Хранится именно число, а не готовая строка: иначе заметки, заведённые до
   * смены языка интерфейса, остались бы с русскими названиями посреди
   * английского меню. Ноль — номера нет, потому что заметка названа.
   */
  autoNumber: number;
  text: string;
  attachments: NoteAttachment[];
  createdAt: number;
  updatedAt: number;
}
